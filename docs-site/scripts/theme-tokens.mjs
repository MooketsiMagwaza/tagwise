/**
 * The app's design tokens for the docs site. Reads src/theme/tokens.css (the
 * one place the app's colours, type and spacing are decided) and rewrites the
 * app's theme selectors for Fumadocs, which marks the theme with a class on
 * <html> (`light` or `dark`) instead of the app's data-theme attribute. The
 * values themselves are untouched, so the docs cannot drift from the app.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const tokensSource = path.resolve(here, '../../src/theme/tokens.css');

export function tokensCss() {
  const css = fs.readFileSync(tokensSource, 'utf8');
  const out = css.replace(/\[data-theme='light'\]/g, '.light').replace(/\[data-theme='dark'\]/g, '.dark');
  if (!out.includes('.dark')) throw new Error(`${tokensSource} has no dark theme block; the docs site expects one.`);
  return `/* Generated by docs-site/scripts/sync-content.mjs from src/theme/tokens.css. Do not edit. */\n\n${out}`;
}
